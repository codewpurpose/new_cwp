/**
 * gen-chapters-sql.mjs — emit `supabase/chapters.sql`, the allowlist of real
 * (course_id, chapter_slug) pairs.
 *
 * Why the database needs its own copy of the curriculum:
 *
 * `progress` rows are written by the browser. Row-level security proves the row
 * belongs to the student writing it, and proves nothing whatsoever about the
 * chapter named in it — so without an allowlist, a signed-in student can insert
 * ten thousand rows for chapters that do not exist and, now that XP is counted
 * from those rows, arrive at any total they like. With one, the ceiling is the
 * real curriculum: every chapter completed, once each.
 *
 * That does not make progress *verified* — someone can still claim a chapter
 * they skimmed, which is indistinguishable from reading it quickly and is not
 * worth defending against. It makes progress *bounded*, which is the property
 * the leaderboard actually needs.
 *
 * Generated rather than hand-written because it has to track the lesson graph,
 * and a stale allowlist silently drops a new chapter's completions on the floor.
 * Regenerate whenever a chapter is published or retired:
 *
 *     npm run learn:sql
 *
 * Reads the same source scan as the validator (scripts/lib/learn-source.mjs), so
 * the two cannot disagree about which chapters are published.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO_ROOT, TRACKS, parseChapters } from "./lib/learn-source.mjs";

const OUT = join(REPO_ROOT, "supabase", "chapters.sql");

/**
 * `--check` compares instead of writing, and exits non-zero on a difference.
 * The validator runs it on every build for one reason: a stale allowlist is a
 * SILENT failure. Publish a chapter, forget to regenerate, and every completion
 * of it is dropped by the trigger — no error anywhere, students just quietly
 * stop earning XP for the newest thing on the site.
 */
const checkOnly = process.argv.includes("--check");

/** Single-quote escaping for a SQL string literal. Slugs are [a-z0-9-], but. */
function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

const rows = [];
for (const track of TRACKS) {
  const source = readFileSync(track.data, "utf8");
  const chapters = parseChapters(source, track.chaptersConst);

  if (chapters.length === 0) {
    console.error(
      `✗ Parsed zero chapters from ${track.chaptersConst}. The data file is ` +
        "probably not at two-space object indentation — see scripts/lib/learn-source.mjs.",
    );
    process.exit(1);
  }

  // Drafts are registered nowhere and reachable by nobody, so a completion for
  // one cannot legitimately exist. Publishing a chapter means regenerating this.
  for (const chapter of chapters.filter((c) => c.status === "published")) {
    rows.push(`  (${sqlString(track.name)}, ${sqlString(chapter.slug)})`);
  }
}

const sql = `-- GENERATED BY scripts/gen-chapters-sql.mjs — DO NOT EDIT BY HAND.
-- Regenerate with: npm run learn:sql
--
-- The allowlist of chapters a student may claim to have completed. See the
-- header of the generator for why this exists, and supabase/schema.sql for the
-- trigger that enforces it.
--
-- Safe to re-run: this replaces the table's contents with the current
-- curriculum. Retiring a chapter removes it here, which leaves any existing
-- \`progress\` rows for it in place (they are already written) but stops new
-- ones being accepted.
--
-- ${rows.length} published chapters across ${TRACKS.length} tracks.

begin;

create table if not exists public.chapters (
  course_id    text not null,
  chapter_slug text not null,
  primary key (course_id, chapter_slug)
);

-- Server-side only, like \`subscribers\`: RLS on, no policies, nothing in the
-- browser reads it. The trigger that consults it is SECURITY DEFINER.
alter table public.chapters enable row level security;

delete from public.chapters;

insert into public.chapters (course_id, chapter_slug) values
${rows.join(",\n")};

commit;
`;

if (checkOnly) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== sql) {
    console.error(
      "✗ supabase/chapters.sql is out of date with the lesson graph.\n" +
        "  Run `npm run learn:sql`, then apply the regenerated file in the\n" +
        "  Supabase SQL editor. Until you do, completions for any chapter\n" +
        "  missing from it are silently discarded and earn no XP.",
    );
    process.exit(1);
  }
  console.log(`chapters.sql: in sync — ${rows.length} published chapters.`);
} else {
  writeFileSync(OUT, sql);
  console.log(`✓ Wrote ${rows.length} chapters to supabase/chapters.sql`);
}
